phase('Поиск')

const results = await pipeline(
  AREAS,
  (area) =>
    agent(area.prompt, {
      label: `аудит:${area.key}`,
      phase: 'Поиск',
      schema: FINDINGS_SCHEMA,
    }).then((r) => ({ area, findings: r?.findings ?? [] })),
  (res) => {
    if (!res || res.findings.length === 0) return { area: res?.area, verified: [] }
    log(`${res.area.label}: найдено ${res.findings.length}, проверяю`)
    return parallel(
      res.findings.map((f) => () =>
        agent(
          `Проект — браузерная Tower Defense в ${ROOT}.

Другой агент утверждает, что нашёл баг. Твоя задача — ОПРОВЕРГНУТЬ его. По умолчанию считай, что находка ошибочна, пока не убедишься в обратном.

ЗАЯВЛЕНИЕ: ${f.title}
Файл: ${f.file}${f.line ? `, строка ${f.line}` : ''}
Почему якобы проблема: ${f.why}
Как якобы воспроизвести: ${f.repro}

Открой указанный файл и связанный код. Проверь:
1. Действительно ли код работает так, как описано? Прочитай, а не предположи.
2. Проявится ли это у реального игрока, или защищено проверкой выше по стеку?
3. Не является ли это осознанным решением с комментарием в коде?

Верни real=false, если находка ошибочна, преувеличена или уже обработана. real=true только если ты сам убедился в дефекте по коду.`,
          {
            label: `проверка:${f.title.slice(0, 30)}`,
            phase: 'Проверка',
            schema: VERDICT_SCHEMA,
          },
        ).then((v) => ({ ...f, area: res.area.label, verdict: v })),
      ),
    ).then((verified) => ({ area: res.area, verified: verified.filter(Boolean) }))
  },
)

const all = results
  .filter(Boolean)
  .flatMap((r) => r.verified ?? [])
  .filter((f) => f.verdict?.real === true)

const order = { критично: 0, важно: 1, мелочь: 2 }
all.sort((a, b) => (order[a.severity] ?? 3) - (order[b.severity] ?? 3))

log(`подтверждено находок: ${all.length}`)

return {
  confirmed: all.map((f) => ({
    severity: f.severity,
    area: f.area,
    title: f.title,
    file: f.file,
    line: f.line ?? null,
    why: f.why,
    repro: f.repro,
    fix: f.fix,
    note: f.verdict?.corrected ?? null,
  })),
}
